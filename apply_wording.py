def git(*args, check=False):
    return subprocess.run(["git", *args], capture_output=True, text=True, check=check)


def main():
    if not (os.path.exists("core/detector_v2.py") and os.path.isdir(".git")):
        sys.exit("Run this from the jnvoy repo folder (the one containing core/ and static/).")
    data = base64.b64decode("".join(PATCH_B64.split()))
    with tempfile.NamedTemporaryFile("wb", suffix=".patch", delete=False) as f:
        f.write(data)
        path = f.name
    if git("apply", "-R", "--check", path).returncode == 0:
        print("Already applied. Nothing to do.")
        return
    check = git("apply", "--check", path)
    if check.returncode != 0:
        print(check.stderr)
        sys.exit("The patch does not fit this copy of the repo. Nothing was changed. "
                 "Run: git status   and   git pull   then try again.")
    git("apply", path, check=True)
    print("Applied. Now run:  pytest -q")


main()
